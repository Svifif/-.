def box(ax, x, y, w, h, title, lines=(), color=C_ROLE, fs=11.8, ls=9.7):
    ax.add_patch(FancyBboxPatch((x - w / 2, y - h / 2), w, h,
                                boxstyle="round,pad=0.05,rounding_size=0.08",
                                fc=color, ec="#2f3b52", lw=1.3, zorder=3))
    top = y + h / 2 - 0.30
    ax.text(x, top, title, ha="center", va="center",
            fontsize=fs, fontweight="bold", zorder=4)
    step = 0.27
    start = top - 0.36
    for i, line in enumerate(lines):
        ax.text(x, start - step * i, line, ha="center", va="center",
                fontsize=ls, zorder=4)


def arrow(ax, p1, p2, label="", style="-|>", ls="-", color="#2f3b52",
          rad=0.0, lpos=0.5, fs=9.2, both=False, dx=0.0, dy=0.12, ha="center"):
    a = FancyArrowPatch(p1, p2, arrowstyle=("<|-|>" if both else style),
                        mutation_scale=13, lw=1.2, color=color,
                        linestyle=ls, connectionstyle=f"arc3,rad={rad}", zorder=2)
    ax.add_patch(a)
    if label:
        lx = p1[0] + (p2[0] - p1[0]) * lpos + dx
        ly = p1[1] + (p2[1] - p1[1]) * lpos + dy
        ax.text(lx, ly, label, ha=ha, va="bottom", fontsize=fs,
                style="italic", color="#1f2a3d", zorder=5,
                bbox=dict(fc="white", ec="none", pad=0.6))


