def comm_graph(path: Path):
    fig, ax = plt.subplots(figsize=(9.4, 5.3))
    ax.set_xlim(0, 12.6)
    ax.set_ylim(0.2, 8.1)
    ax.axis("off")

    clients = [7.0, 5.5, 4.0]
    workers = [("node-a", 7.3), ("node-b", 5.9),
               ("node-gpu", 4.5), ("node-legacy", 3.1)]
    bx, by = 6.2, 5.2

    def node(x, y, w, h, text, color):
        ax.add_patch(FancyBboxPatch((x - w / 2, y - h / 2), w, h,
                                    boxstyle="round,pad=0.03,rounding_size=0.06",
                                    fc=color, ec="#2f3b52", lw=1.2, zorder=3))
        ax.text(x, y, text, ha="center", va="center", fontsize=11.4,
                fontweight="bold", zorder=4)

    for i, y in enumerate(clients, 1):
        node(1.7, y, 2.1, 0.60, f"Заказчик {i}", C_ROLE)
    for name, y in workers:
        node(10.9, y, 2.1, 0.60, name, C_AGENT)
    node(bx, by, 2.30, 0.80, "Брокер", C_ROLE)
    node(3.4, 1.50, 2.1, 0.60, "Арбитр", C_EXT)
    node(9.0, 1.50, 2.1, 0.60, "Монитор", C_EXT)

    # заказчики: запросы к брокеру и ответы
    in_y = [5.50, 5.24, 4.98]
    out_y = [5.36, 5.10, 4.86]
    for i, y in enumerate(clients):
        arrow(ax, (2.76, y - 0.02), (5.03, in_y[i]),
              "request / SLA" if i == 0 else "", lpos=0.40, fs=9.4, dy=0.10, dx=0.16)
        arrow(ax, (5.03, out_y[i]), (2.76, y - 0.18),
              "result" if i == 0 else "", lpos=0.68, fs=9.4, ls="--", dy=-0.36)

    # исполнители: запросы предложений и подтверждения
    cfp_y = [5.54, 5.34, 5.14, 4.94]
    ack_y = [5.44, 5.26, 5.06, 4.88]
    for i, (name, y) in enumerate(workers):
        top = i in (0, 1)
        arrow(ax, (7.38, cfp_y[i]), (9.82, y + (0.12 if top else -0.12)),
              "cfp / award" if i == 1 else "", lpos=0.55, fs=9.4, dy=0.06)
        arrow(ax, (9.82, y + (-0.15 if top else 0.15)), (7.38, ack_y[i]),
              "propose / inform" if i == 1 else "", lpos=0.45, fs=9.4,
              ls="--", dy=-0.32)

    # арбитраж
    arrow(ax, (5.55, 4.80), (3.95, 1.82), "request-arbitration", lpos=0.50,
          fs=9.4, dx=-0.95, dy=0.06)
    arrow(ax, (4.10, 1.82), (5.95, 4.80), "arbitration-result", lpos=0.55,
          fs=9.4, ls="--", dx=0.80, dy=-0.30)

    # телеметрия монитору и проверка доступности
    arrow(ax, (8.30, 1.82), (6.95, 4.80), "inform (trace)", lpos=0.5, fs=9.4,
          dx=0.62, dy=0.0, ls=":")
    arrow(ax, (9.72, 1.82), (10.45, 2.79), "", ls="-.")
    arrow(ax, (10.65, 2.79), (9.92, 1.84), "", ls="-.")

    ax.text(0.30, 0.50, "— протокол распределения;  - - подтверждение/ответ;  "
                        ": аудит;  -. проверка доступности (request-probe / inform-probe)",
            fontsize=8.0, style="italic", color="#44506b")

    ax.set_title("Граф коммуникаций МАС DiSMA (перформативы FIPA-ACL)", fontsize=14.0,
                 fontweight="bold")
    fig.savefig(path, dpi=200, bbox_inches="tight", pad_inches=0.10)
    plt.close(fig)


