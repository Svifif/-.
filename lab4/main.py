        f"до {a['makespan']:.0f} тиков, при этом сообщений тратится минимум "
        f"({a['messages']:.0f}) — дефект маскируется «экономичностью». Защита "
        f"состоит в мандатном токене: делегату разрешено не более одного "
        f"задания в работе и на срок 5 тиков, после чего право возвращается "
