OUT = Path(__file__).resolve().parent / "out"
OUT.mkdir(exist_ok=True)
plt.rcParams["font.family"] = "DejaVu Sans"
plt.rcParams["legend.framealpha"] = 1.0

SEEDS = [1, 2, 3]
KEYS = ["sla_rate", "makespan", "messages", "failed", "reassigns"]
SHORT = {"S0": "S0 контроль", "S1": "S1 ложный отчёт",
         "S2": "S2 подмена цели", "S3": "S3 отказ средства",
         "S4": "S4 полномочия", "S5": "S5 цикл",
         "S6": "S6 противоречия", "S7": "S7 инструкции"}


def experiment() -> dict:
    res = {}
    for sid in M.SCENARIOS:
        for defense in (False, True):
            runs = [M.run(sid, defense=defense, seed=s) for s in SEEDS]
            agg = {k: st.mean(r[k] for r in runs) for k in KEYS}
            agg["detected"] = sum(1 for r in runs if r["detected"])
            agg["detect_at"] = st.mean([r["detect_at"] for r in runs
                                        if r["detect_at"] is not None] or [0])
            agg["trace"] = runs[0]["trace"]
            res[(sid, defense)] = agg
    return res


def figures(res):
    ids = list(M.SCENARIOS)
    fig, ax = plt.subplots(figsize=(11.4, 4.6))
    x = range(len(ids))
    w = 0.38
    attack = [res[(s, False)]["sla_rate"] * 100 for s in ids]
    defense = [res[(s, True)]["sla_rate"] * 100 for s in ids]
    ax.bar([i - w / 2 for i in x], attack, width=w, color="#c98383",
           edgecolor="#333", linewidth=0.5, label="атака без защиты")
    ax.bar([i + w / 2 for i in x], defense, width=w, color="#8fbf8f",
           edgecolor="#333", linewidth=0.5, label="атака с защитой")
    ax.axhline(res[("S0", False)]["sla_rate"] * 100, color="#333", ls="--", lw=1.2,
               label="контроль (без атаки)")
    ax.set_xticks(list(x))
    ax.set_xticklabels([SHORT[s] for s in ids], rotation=18, ha="right", fontsize=8)
    ax.set_ylabel("Нарушения SLA, %")
    ax.set_title("Ущерб от неблагоприятных сценариев до и после введения защиты",
                 fontsize=10)
    ax.legend(fontsize=8)
    ax.grid(axis="y", ls=":", alpha=0.5)
    fig.tight_layout()
    fig.savefig(OUT / "fig4_damage.png", dpi=190)
    plt.close(fig)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11.4, 4.2))
    lost_a = [res[(s, False)]["failed"] for s in ids]
    lost_d = [res[(s, True)]["failed"] for s in ids]
    ax1.bar([i - w / 2 for i in x], lost_a, width=w, color="#c98383",
            edgecolor="#333", lw=0.5, label="без защиты")
    ax1.bar([i + w / 2 for i in x], lost_d, width=w, color="#8fbf8f",
            edgecolor="#333", lw=0.5, label="с защитой")
    ax1.set_xticks(list(x))
    ax1.set_xticklabels([s for s in ids], fontsize=8)
    ax1.set_ylabel("Потерянных заданий")
    ax1.set_title("Потери заданий", fontsize=10)
    ax1.legend(fontsize=8)
    ax1.grid(axis="y", ls=":", alpha=0.5)

    msg_a = [res[(s, False)]["messages"] for s in ids]
    msg_d = [res[(s, True)]["messages"] for s in ids]
    ax2.bar([i - w / 2 for i in x], msg_a, width=w, color="#c98383",
            edgecolor="#333", lw=0.5, label="без защиты")
    ax2.bar([i + w / 2 for i in x], msg_d, width=w, color="#8fbf8f",
            edgecolor="#333", lw=0.5, label="с защитой")
    ax2.set_xticks(list(x))
    ax2.set_xticklabels([s for s in ids], fontsize=8)
    ax2.set_ylabel("Сообщений")
    ax2.set_title("Накладные расходы на защиту", fontsize=10)
    ax2.legend(fontsize=8)
    ax2.grid(axis="y", ls=":", alpha=0.5)
    fig.tight_layout()
    fig.savefig(OUT / "fig4_losses.png", dpi=190)
    plt.close(fig)


def build_report(res):
    r = Report(4, "Диверсионный анализ и оценка надёжности "
                  "многоагентной системы")
    r.title_page()

    r.h1("1. Методика диверсионного анализа")
    r.p("Диверсионный анализ выполняется в три этапа: 1) для каждого "
        "неблагоприятного сценария фиксируется дефект — конкретное допущение "
        "системы, которое позволяет сценарию нанести ущерб; 2) сценарий "
        "запускается на базовой системе, собирается трасса выполнения и "
        "измеряется ущерб; 3) вводится защитный механизм, сценарий повторяется "
        "на тех же данных, и ущерб сравнивается. Контрольный прогон S0 без атаки "
        "задаёт эталонные показатели.")
    r.p("Используется система DiSMA с обратным аукционом в качестве основного "
        "механизма распределения и потоком из 90 заданий средней интенсивности. "
        "Каждый сценарий выполняется на трёх фиксированных генераторах "
        "(seed = 1…3); в таблицах — средние значения. Измеряются: доля нарушений "
        "директивных сроков, время завершения потока, число потерянных "
        "(невыполненных) заданий, число сообщений (накладные расходы защиты), "
        "факт и время обнаружения инцидента.")
    r.table(
        ["Код", "Неблагоприятный сценарий", "Дефект системы", "Защитный механизм"],
        [[sid, cfg["name"], cfg["flaw"], cfg["defense"]]
         for sid, cfg in M.SCENARIOS.items()],
        caption="Набор неблагоприятных сценариев и защитных механизмов",
        widths=[1.3, 4.2, 5.2, 5.2], font=8.5,
    )

    r.h1("2. Результаты")
    rows = []
    for sid in M.SCENARIOS:
        a, d = res[(sid, False)], res[(sid, True)]
        rows.append([
            sid,
            f"{a['sla_rate'] * 100:.1f}",
            f"{d['sla_rate'] * 100:.1f}",
            f"{a['failed']:.0f} / {d['failed']:.0f}",
            f"{a['makespan']:.0f} / {d['makespan']:.0f}",
            f"{a['messages']:.0f} / {d['messages']:.0f}",
            ("да" if d["detected"] else "нет"),
        ])
    r.table(["Код", "SLA без защ., %", "SLA с защ., %", "Потери (без/с)",
             "Makespan (без/с)", "Сообщений (без/с)", "Обнаружено"],
            rows, caption="Ущерб от сценариев и эффект защитных механизмов "
                          "(среднее по 3 прогонам)",
            widths=[1.3, 2.0, 2.0, 2.2, 2.5, 2.6, 2.4], font=9)
    figures(res)
    r.figure(OUT / "fig4_damage.png",
             "Нарушения директивных сроков по сценариям", 16.5)
    r.figure(OUT / "fig4_losses.png",
             "Потери заданий и накладные расходы на защиту", 16.0)

    r.h1("3. Анализ по сценариям")
    s0 = res[("S0", False)]
