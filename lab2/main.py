from __future__ import annotations

import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from mas.mechanisms import make
from mas.model import Sim, generate_jobs, make_cluster
from mas.report import Report

OUT = Path(__file__).resolve().parent / "out"
OUT.mkdir(exist_ok=True)
plt.rcParams["font.family"] = "DejaVu Sans"
plt.rcParams["legend.framealpha"] = 1.0

MECHS = ["cd", "cnp", "auction"]
NAMES = {"cd": "Централизованная\nдиспетчеризация", "cnp": "Контрактная\nсеть",
         "auction": "Обратный\nаукцион"}
SHORT = {"cd": "ЦД", "cnp": "КС", "auction": "ОА"}
PROFILES = ["light", "medium", "heavy"]
PROF_NAMES = {"light": "лёгкая (ρ≈0,55)", "medium": "средняя (ρ≈0,80)",
              "heavy": "тяжёлая (ρ≈1,05)"}
SEEDS = list(range(1, 6))
COLORS = {"cd": "#8fa8c8", "cnp": "#e0b070", "auction": "#8fbf8f"}
N_JOBS = 120


def run_all() -> dict:
    res = {}
    for prof in PROFILES:
        for m in MECHS:
            runs = []
            for seed in SEEDS:
                jobs = generate_jobs(N_JOBS, seed=seed, profile=prof)
                sim = Sim(jobs, make_cluster(), make(m), seed=seed)
                runs.append(sim.run().metrics())
            res[(prof, m)] = {k: st.mean(r[k] for r in runs) for k in runs[0]}
    return res


def fig_overview(res, path):
    fig, axes = plt.subplots(2, 2, figsize=(11.0, 7.2))
    panels = [
        ("sla_rate", "Доля нарушений SLA, %", 100.0),
        ("msg_per_job", "Сообщений на задание", 1.0),
        ("makespan", "Время завершения потока, тиков", 1.0),
        ("exec_cost", "Стоимость выполнения, усл. ед.", 1.0),
    ]
    x = range(len(PROFILES))
    w = 0.26
    for ax, (key, title, scale) in zip(axes.flat, panels):
        for i, m in enumerate(MECHS):
            vals = [res[(p, m)][key] * scale for p in PROFILES]
            ax.bar([xx + (i - 1) * w for xx in x], vals, width=w,
                   color=COLORS[m], edgecolor="#333", linewidth=0.5,
                   label={"cd": "централизованная диспетчеризация",
                          "cnp": "контрактная сеть",
                          "auction": "обратный аукцион"}[m])
        ax.set_xticks(list(x))
        ax.set_xticklabels([PROF_NAMES[p] for p in PROFILES], fontsize=8)
        ax.set_title(title, fontsize=10)
        ax.grid(axis="y", ls=":", alpha=0.5)
    axes.flat[0].legend(fontsize=8, loc="upper left")
    fig.suptitle("Сравнение механизмов распределения заданий", fontsize=12,
                 fontweight="bold")
    fig.tight_layout()
    fig.savefig(path, dpi=190)
    plt.close(fig)


def fig_tradeoff(res, path):
    fig, ax = plt.subplots(figsize=(7.4, 4.6))
    for m in MECHS:
        xs = [res[(p, m)]["coord_cost"] for p in PROFILES]
        ys = [res[(p, m)]["sla_rate"] * 100 for p in PROFILES]
        ax.plot(xs, ys, "o-", color=COLORS[m], label=SHORT[m], ms=7)
        for x_, y_, p in zip(xs, ys, PROFILES):
            ax.annotate(p, (x_, y_), fontsize=7, xytext=(4, 4),
                        textcoords="offset points")
    ax.set_xlabel("Стоимость координации, усл. ед.")
    ax.set_ylabel("Нарушения SLA, %")
    ax.set_title("Компромисс «стоимость координации — качество обслуживания»",
                 fontsize=10)
    ax.grid(ls=":", alpha=0.6)
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=190)
    plt.close(fig)


